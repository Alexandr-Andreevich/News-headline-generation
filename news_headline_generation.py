# График потерь
def loss_history(trainer):
    log_history = trainer.state.log_history

    train_epochs, train_losses = [], []
    eval_epochs, eval_losses = [], []

    for log in log_history:
        if "loss" in log and "epoch" in log:
            train_epochs.append(log["epoch"])
            train_losses.append(log["loss"])
        elif "eval_loss" in log and "epoch" in log:
            eval_epochs.append(log["epoch"])
            eval_losses.append(log["eval_loss"])

    plt.figure(figsize=(8, 5))
    plt.plot(train_epochs, train_losses, label="Train Loss", marker="o")
    plt.plot(eval_epochs, eval_losses, label="Validation Loss", marker="s")
    plt.title("Динамика потерь (Loss) по эпохам")
    plt.xlabel("Эпоха")
    plt.ylabel("Loss")
    plt.legend()
    plt.grid(True)
    plt.show()

loss_history(trainer)

