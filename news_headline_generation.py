def generate_title(text, max_new_tokens=20):
    prompt = f"Текст: {text}\nЗаголовок:"
    device = model.device
    inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=MAX_LEN - max_new_tokens).to(device)

    model.eval()
    with torch.no_grad():
        output_tokens = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            pad_token_id=tokenizer.eos_token_id,
            eos_token_id=tokenizer.eos_token_id,
            do_sample=False
        )

    gen_tokens = output_tokens[0][inputs["input_ids"].shape[1]:]
    pred_title = tokenizer.decode(gen_tokens, skip_special_tokens=True).strip()
    pred_title = pred_title.split("\n")[0].strip()

    pred_title_del_teg = re.split(r'\s+[-—]\s+', pred_title)[0].strip()
    return pred_title_del_teg

