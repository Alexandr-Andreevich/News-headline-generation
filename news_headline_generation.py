NUM_SAMPLES = 3000
MAX_LEN = 256
RANDOM_STATE = 20
MODEL_NAME = "sberbank-ai/rugpt3medium_based_on_gpt2"

def sample_dataset(dataset, n_samples, random_state):
    if len(dataset) <= n_samples:
        return dataset
    return dataset.select(range(n_samples))


def clean_text(raw_html: str) -> str:
    if not isinstance(raw_html, str):
        return ""
    # Декодируем HTML-сущности
    text = html.unescape(raw_html)
    # Удаляем теги
    text = re.sub(r"<[^<]+?>", " ", text)
    # Нормализуем пробелы
    text = re.sub(r"\s+", " ", text).strip()
    return text


def format_example(text, title):
    return f"Текст: {text}\nЗаголовок: {title}{eos}"


def tokenize_function(examples):
    formatted = []
    for t, tl in zip(examples["text"], examples["title"]):
        # Обрезаем текст до 256 токенов
        t_short = " ".join(t.split()[:150])  # ~250–300 символов
        formatted.append(f"Текст: {t_short}\nЗаголовок: {tl}{eos}")
    return tokenizer(
        formatted,
        truncation=True,
        max_length=MAX_LEN,
        padding=True
    )

# Берём не более NUM_SAMPLES из каждого сплита
train_ds = sample_dataset(ds["train"], NUM_SAMPLES, RANDOM_STATE)
